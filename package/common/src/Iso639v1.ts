export function getLanguageName(code: string): string | undefined {
  return Iso639v1[code as keyof typeof Iso639v1]?.name
}

export function sortLanguageCodesByName(codes: string[]): string[] {
  return [...codes].sort((a, b) =>
    (getLanguageName(a) || a).localeCompare(getLanguageName(b) || b),
  )
}
